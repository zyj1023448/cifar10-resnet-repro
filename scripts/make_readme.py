"""Generate README.md from results/summary.json so numbers never diverge from logs."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = json.loads((ROOT / "results" / "summary.json").read_text(encoding="utf8"))
G = SUMMARY["groups"]


def row(name: str) -> str:
    s = G[name]
    return (f"| {name} | {s['acc_mean']:.2f} ± {s['acc_std']:.2f} | {s['f1_mean']:.2f} | "
            f"{s['ece_mean']:.4f} | {s['nll_mean']:.4f} | {s['params']/1e6:.3f} | "
            f"{s['time_mean_s']/60:.1f} | {s['n']} |")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-url", default="https://github.com/REPLACE_ME/cifar10-resnet-repro")
    args = ap.parse_args()
    rows = "\n".join(row(n) for n in ["Plain-20", "ResNet-20", "SE-ResNet-20"] if n in G)
    depth_rows = "\n".join(row(n) for n in ["Plain-20", "Plain-56", "ResNet-20", "ResNet-56", "SE-ResNet-56"] if n in G)
    p = SUMMARY["paired"]["ResNet-20_vs_Plain-20"]
    p2 = SUMMARY["paired"]["SE-ResNet-20_vs_ResNet-20"]

    weights = sorted((ROOT / "weights").glob("*.pt"))
    lines = [
        "# CIFAR-10 Residual Learning and Channel Attention Reproduction",
        "",
        "Code, training logs and trained weights for the paper **“残差学习与通道注意力在 CIFAR-10 图像分类中的"
        "复现与实证分析”** (Residual Learning and Channel Attention for CIFAR-10 Classification: "
        "A Reproduction and Empirical Analysis).",
        "",
        f"**Paper:** `paper/CIFAR10_ResNet_SE_复现与实证分析.pdf`  ",
        f"**Code and weights:** {args.repo_url}",
        "",
        "This is a deliberately small, single-GPU reproduction. It is **not** a new architecture paper: "
        "it asks how much of the gain of a residual network comes from the residual path, and how much "
        "channel attention adds on a 0.27M-parameter CIFAR backbone under a fixed 100-epoch budget.",
        "",
        "## Results at a glance",
        "",
        "| Method | Test acc (%) | Macro-F1 (%) | ECE | NLL | Params (M) | Train (min) | Seeds |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        rows,
        "",
        f"- Residual gain over the plain baseline: **{G['ResNet-20']['acc_mean'] - G['Plain-20']['acc_mean']:+.2f} pp** "
        f"(McNemar p = {p['mcnemar']['p_value']:.4g}; bootstrap 95% CI "
        f"[{p['bootstrap_diff_pp'][0]:.2f}, {p['bootstrap_diff_pp'][1]:.2f}] pp).",
        f"- SE gain over ResNet-20: **{G['SE-ResNet-20']['acc_mean'] - G['ResNet-20']['acc_mean']:+.2f} pp** "
        f"(p = {p2['mcnemar']['p_value']:.4g}; CI [{p2['bootstrap_diff_pp'][0]:.2f}, "
        f"{p2['bootstrap_diff_pp'][1]:.2f}] pp), but ECE drops from "
        f"{G['ResNet-20']['ece_mean']:.4f} to {G['SE-ResNet-20']['ece_mean']:.4f}.",
        "- Depth 56: the plain network degrades, the residual network improves. See `results/figures/fig_depth.png`.",
        "",
        "## Depth study",
        "",
        "| Method | Test acc (%) | Macro-F1 (%) | ECE | NLL | Params (M) | Train (min) | Seeds |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        depth_rows,
        "",
        "## Repository layout",
        "",
        "```text",
        "src/          data, models, training loop, metrics, analysis, Grad-CAM",
        "scripts/      dataset preparation, experiment grid, reproduce.ps1/sh, keep-awake helper",
        "weights/      one .pt per run (state_dict + config + final metrics)",
        "results/runs/ per-run JSON (config, per-epoch history, final metrics)",
        "results/preds/per-sample test logits and labels (.npz)",
        "results/figures/paper figures (PNG, 200–300 dpi)",
        "results/tables/ CSV tables used in the paper",
        "paper/        DOCX/PDF and the scripts that build them",
        "data/         CIFAR-10 cache (git-ignored; regenerated by scripts/prepare_cifar.py)",
        "```",
        "",
        f"`weights/` contains {len(weights)} checkpoints. `weights/plain20_s42.pt` is the plain baseline; "
        "`weights/se20_s42.pt` is the proposed SE-ResNet-20; `weights/resnet20_s42.pt` is the reproduced "
        "ResNet-20. Each checkpoint stores `state_dict`, the training config and the final metrics.",
        "",
        "## Quick start",
        "",
        "```bash",
        "python -m venv .venv",
        "# Windows: .venv\\Scripts\\activate",
        "pip install -r requirements.txt",
        "python scripts/prepare_cifar.py    # downloads CIFAR-10 (~135 MB) and caches tensors",
        "python scripts/run_grid.py         # 25 runs, ~3 h on one RTX 5060 Laptop GPU",
        "python -m src.analyze              # tables, figures, McNemar/bootstrap, robustness",
        "python paper/build_paper.py        # regenerate the DOCX from results/summary.json",
        "```",
        "",
        "To check the committed artefacts without retraining:",
        "",
        "```bash",
        "python scripts/validate_results.py",
        "```",
        "",
        "## Environment",
        "",
        "- NVIDIA GeForce RTX 5060 Laptop GPU (8 GB), CUDA 12.8, PyTorch 2.11.0+cu128, Python 3.13.",
        "- 100 epochs, batch 256, SGD (momentum 0.9, Nesterov), weight decay 5e-4, cosine schedule with "
        "5-epoch warmup, bfloat16 autocast.",
        "- 20-layer runs take 5–7 min; 56-layer runs take 17–19 min. Results are the last-epoch test "
        "accuracy (no test-time model selection), averaged over seeds.",
        "",
        "## License",
        "",
        "MIT. See `LICENSE`.",
        "",
    ]
    out = ROOT / "README.md"
    out.write_text("\n".join(lines), encoding="utf8")
    print("saved", out)

    # checksums for weights
    sums = []
    for w in weights:
        h = hashlib.sha256(w.read_bytes()).hexdigest()
        sums.append(f"{h}  {w.name}")
    (ROOT / "weights" / "SHA256SUMS.txt").write_text("\n".join(sums) + "\n", encoding="utf8")
    print("saved weights/SHA256SUMS.txt")


if __name__ == "__main__":
    main()
